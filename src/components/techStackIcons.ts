  // Frameworks & Libraries
  if (lower === "pytorch") return "pytorch";
  if (lower === "tensorflow") return "tensorflow";
  if (lower.includes("scikit")) return "scikitlearn";
  if (lower.includes("langchain")) return "langchain";
